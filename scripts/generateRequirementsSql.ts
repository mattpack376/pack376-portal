/*
 * Writes a migration that loads (or refreshes) every adventure requirement
 * from prisma/advancement-requirements/*.json:
 *
 *   npx tsx scripts/generateRequirementsSql.ts 20261118120001_adventure_requirements_data
 *
 * Production only migrates (scripts/vercel-build.mjs), so this is how the
 * requirement list reaches the live site. The SQL is idempotent: rows are
 * matched on (adventureId, code) and updated in place, so a later data fix is
 * a new generated migration, never an edit to an applied one. Adventures are
 * found by rank + name; one the database doesn't have is skipped rather than
 * failing the deploy. Requirements the JSON no longer lists are left alone
 * (deleting them would delete scouts' checks on them).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadRequirementRows } from "../prisma/requirementsData";

const name = process.argv[2];
if (!name || !/^\d{14}_[a-z0-9_]+$/.test(name)) {
  console.error("Usage: npx tsx scripts/generateRequirementsSql.ts <YYYYMMDDHHMMSS_migration_name>");
  process.exit(1);
}

const sqlString = (value: string | null) => (value === null ? "NULL" : `'${value.replace(/'/g, "''")}'`);
const sqlInt = (value: number | null) => (value === null ? "NULL::integer" : `${Math.trunc(value)}::integer`);

const { requirements, adventures } = loadRequirementRows();

const lines: string[] = [
  "-- Generated by scripts/generateRequirementsSql.ts from prisma/advancement-requirements/*.json.",
  "-- Do not edit by hand: change the JSON and generate a new migration.",
  `-- ${adventures.length} adventures, ${requirements.length} requirements.`,
  "",
  "-- Each adventure's alternate way to earn it (e.g. a religious emblem) and how many",
  "-- top-level requirements it needs (NULL = all).",
  'UPDATE "Adventure" AS a SET "requirementsNote" = v.note, "requirementsPick" = v.pick',
  "FROM (VALUES",
  adventures
    .map(
      (a) =>
        `  (${sqlString(a.rank)}, ${sqlString(a.adventureName)}, ${a.requirementsNote === null ? "NULL::text" : sqlString(a.requirementsNote)}, ${sqlInt(a.requirementsPick)})`,
    )
    .join(",\n"),
  ") AS v(rank, name, note, pick)",
  'WHERE a."rank" = v.rank::"Rank" AND a."name" = v.name;',
  "",
];

// Parents come before their children (loadRequirementRows walks top-down), so
// one statement per tree level keeps every parentId pointing at a row that
// already exists. Today's data is a single level.
const depth = new Map<string, number>();
for (const row of requirements) depth.set(row.id, row.parentId ? (depth.get(row.parentId) ?? 0) + 1 : 0);
const levels = [...new Set(depth.values())].sort((a, b) => a - b);

for (const level of levels) {
  const rows = requirements.filter((r) => depth.get(r.id) === level);
  lines.push(
    `-- Requirements, tree level ${level} (${rows.length} rows).`,
    'INSERT INTO "AdventureRequirement" ("id", "adventureId", "parentId", "code", "text", "pick", "isGroup", "sortOrder")',
    'SELECT v.id, a."id", v.parent_id, v.code, v.text, v.pick, v.is_group, v.sort_order',
    "FROM (VALUES",
    rows
      .map(
        (r) =>
          `  (${sqlString(r.id)}, ${sqlString(r.rank)}, ${sqlString(r.adventureName)}, ${r.parentId === null ? "NULL::text" : sqlString(r.parentId)}, ${sqlString(r.code)}, ${sqlString(r.text)}, ${sqlInt(r.pick)}, ${r.isGroup ? "TRUE" : "FALSE"}, ${sqlInt(r.sortOrder)})`,
      )
      .join(",\n"),
    ") AS v(id, rank, adventure_name, parent_id, code, text, pick, is_group, sort_order)",
    'JOIN "Adventure" a ON a."rank" = v.rank::"Rank" AND a."name" = v.adventure_name',
    'ON CONFLICT ("adventureId", "code") DO UPDATE SET',
    '  "parentId" = EXCLUDED."parentId",',
    '  "text" = EXCLUDED."text",',
    '  "pick" = EXCLUDED."pick",',
    '  "isGroup" = EXCLUDED."isGroup",',
    '  "sortOrder" = EXCLUDED."sortOrder";',
    "",
  );
}

const dir = path.join(__dirname, "..", "prisma", "migrations", name);
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "migration.sql"), lines.join("\n"), "utf8");
console.log(`Wrote ${path.relative(process.cwd(), path.join(dir, "migration.sql"))}: ${adventures.length} adventures, ${requirements.length} requirements.`);
